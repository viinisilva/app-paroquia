// "Fl 4,10-19" → "Filipenses 4,10-19"; também dentro de parênteses e refrões: "(R. Is 61,10b)".
// "SI" (i maiúsculo) é erro de digitação frequente na fonte para "Sl". Abreviação desconhecida fica como veio.
export function formatBibleReference(value: string) {
  return value.replace(
    /(^|[\s(;])([1-3])?\s?(SI|[A-ZÁÉÍÓÚ][a-záéíóúâêô]{0,3})(?=\s*\d)\s*/g,
    (match, before: string, ordinal: string | undefined, book: string) => {
      const name = BOOKS[(ordinal ?? '') + (book === 'SI' ? 'Sl' : book)];
      return name ? `${before}${name} ` : match;
    },
  );
}
